UPGRADE_SQL = """
-- Needed so a GiST index can combine "resource_id =" with a range overlap.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash TEXT         NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT ck_users_role CHECK (role IN ('STUDENT', 'STAFF', 'ADMIN'))
);
-- Case-insensitive unique email.
CREATE UNIQUE INDEX uq_users_email_lower ON users (lower(email));

CREATE TABLE user_sessions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id            BIGINT      NOT NULL,
    session_token_hash CHAR(64)    NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at         TIMESTAMPTZ NOT NULL,
    revoked_at         TIMESTAMPTZ NULL,
    last_seen_at       TIMESTAMPTZ NULL,
    CONSTRAINT pk_user_sessions PRIMARY KEY (id),
    CONSTRAINT fk_user_sessions_user_id_users FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT uq_user_sessions_session_token_hash UNIQUE (session_token_hash),
    CONSTRAINT ck_user_sessions_expires_after_created CHECK (expires_at > created_at)
);
CREATE INDEX ix_user_sessions_user_id ON user_sessions (user_id);

CREATE TABLE resources (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(100) NOT NULL,
    type        VARCHAR(30)  NOT NULL,
    description TEXT         NULL,
    location    VARCHAR(150) NULL,
    capacity    INTEGER      NULL,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    opens_at    TIME         NOT NULL,
    closes_at   TIME         NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_resources PRIMARY KEY (id),
    CONSTRAINT ck_resources_capacity_positive CHECK (capacity IS NULL OR capacity > 0),
    CONSTRAINT ck_resources_opening_hours CHECK (opens_at < closes_at)
);

CREATE TABLE reservations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id             BIGINT      NOT NULL,
    resource_id         BIGINT      NOT NULL,
    start_time          TIMESTAMPTZ NOT NULL,
    end_time            TIMESTAMPTZ NOT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',
    qr_token_hash       CHAR(64)    NOT NULL,
    qr_token_ciphertext TEXT        NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    cancellation_reason VARCHAR(40) NULL,
    CONSTRAINT pk_reservations PRIMARY KEY (id),
    CONSTRAINT fk_reservations_user_id_users FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_resource_id_resources FOREIGN KEY (resource_id) REFERENCES resources (id) ON DELETE RESTRICT,
    CONSTRAINT uq_reservations_qr_token_hash UNIQUE (qr_token_hash),
    CONSTRAINT ck_reservations_status CHECK (status IN ('CONFIRMED', 'CHECKED_IN', 'CANCELLED', 'NO_SHOW')),
    CONSTRAINT ck_reservations_time_order CHECK (end_time > start_time),
    CONSTRAINT ck_reservations_max_duration CHECK (end_time - start_time <= interval '120 minutes'),
    -- R3: no two CONFIRMED/CHECKED_IN bookings of one resource may overlap, even under
    -- concurrent requests. '[)' = half-open, so 10:00-11:00 and 11:00-12:00 are both allowed.
    CONSTRAINT no_active_overlap EXCLUDE USING gist (
        resource_id WITH =,
        tstzrange(start_time, end_time, '[)') WITH &&
    ) WHERE (status IN ('CONFIRMED', 'CHECKED_IN'))
);
CREATE INDEX ix_reservations_user_id_start_time ON reservations (user_id, start_time);
CREATE INDEX ix_reservations_resource_id_start_time ON reservations (resource_id, start_time);
-- Used by the no-show job: CONFIRMED reservations whose start has passed.
CREATE INDEX ix_reservations_status_start_time ON reservations (status, start_time);

CREATE TABLE check_ins (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_id BIGINT      NOT NULL,
    verified_by    BIGINT      NOT NULL,
    checked_in_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_check_ins PRIMARY KEY (id),
    CONSTRAINT fk_check_ins_reservation_id_reservations FOREIGN KEY (reservation_id) REFERENCES reservations (id) ON DELETE RESTRICT,
    CONSTRAINT fk_check_ins_verified_by_users FOREIGN KEY (verified_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT uq_check_ins_reservation_id UNIQUE (reservation_id)
);

CREATE TABLE resource_unavailability (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    resource_id BIGINT       NOT NULL,
    starts_at   TIMESTAMPTZ  NOT NULL,
    ends_at     TIMESTAMPTZ  NOT NULL,
    reason      VARCHAR(255) NULL,
    created_by  BIGINT       NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_resource_unavailability PRIMARY KEY (id),
    CONSTRAINT fk_resource_unavailability_resource_id_resources FOREIGN KEY (resource_id) REFERENCES resources (id) ON DELETE RESTRICT,
    CONSTRAINT fk_resource_unavailability_created_by_users FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_resource_unavailability_time_order CHECK (ends_at > starts_at)
);
CREATE INDEX ix_resource_unavailability_resource_id_starts_at ON resource_unavailability (resource_id, starts_at);
"""

